/// Submits feedback to the backend and maps transport errors for the UI.
library;

import 'package:cloud_firestore/cloud_firestore.dart';

import '../models/feedback_entry.dart';
import 'feedback_doc_writer.dart';

/// Why a feedback submission did not visibly succeed.
enum FeedbackSendFailure {
  /// The document was already written by an earlier attempt.
  alreadyRecorded,

  /// The backend refused the payload.
  rejected,

  /// The backend could not be reached.
  unreachable,

  /// Any other error.
  unknown,
}

/// A send failure mapped to a stable reason.
class FeedbackSendException implements Exception {
  const FeedbackSendException(this.failure, {this.cause, this.stackTrace});

  /// The reason the submission did not visibly succeed.
  final FeedbackSendFailure failure;

  /// The original error, kept for debugging; never shown to the user.
  final Object? cause;

  /// Where [cause] was thrown.
  final StackTrace? stackTrace;

  @override
  String toString() => 'FeedbackSendException($failure)';
}

/// Sends a validated feedback entry to the backend.
abstract interface class FeedbackService {
  /// Submits [entry], throwing [FeedbackSendException] on failure.
  Future<void> send(FeedbackEntry entry);

  /// Prepares the transport so a send does not pay for initialization.
  ///
  /// Never called at app startup; the sheet warms the transport when it opens.
  Future<void> warmUp();
}

/// Sends feedback through [writer].
///
/// The document id is generated by the client and is stable across retries, so
/// a `permission-denied` on a retry means the earlier write already landed
/// (the rules allow `create` only) — but only when that earlier attempt could
/// have reached the server. A retry after a rejected payload means nothing was
/// written, so the denial stays a rejection.
class FirestoreFeedbackService implements FeedbackService {
  const FirestoreFeedbackService(this.writer);

  /// The transport that writes the document.
  final FeedbackDocWriter writer;

  @override
  Future<void> warmUp() => writer.warmUp();

  @override
  Future<void> send(FeedbackEntry entry) async {
    try {
      await writer.create(entry.docId, {
        ...entry.toMap(),
        'createdAt': FieldValue.serverTimestamp(),
      });
    } on FirebaseException catch (error, stackTrace) {
      throw FeedbackSendException(
        _mapFailure(error.code, entry.possiblyWritten),
        cause: error,
        stackTrace: stackTrace,
      );
    } catch (error, stackTrace) {
      throw FeedbackSendException(
        FeedbackSendFailure.unknown,
        cause: error,
        stackTrace: stackTrace,
      );
    }
  }

  static FeedbackSendFailure _mapFailure(String code, bool possiblyWritten) {
    switch (code) {
      case 'permission-denied':
        return possiblyWritten
            ? FeedbackSendFailure.alreadyRecorded
            : FeedbackSendFailure.rejected;
      case 'unavailable':
      case 'deadline-exceeded':
        return FeedbackSendFailure.unreachable;
      default:
        return FeedbackSendFailure.unknown;
    }
  }
}
